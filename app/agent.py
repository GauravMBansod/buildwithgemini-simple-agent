def generate_recipe_image(prompt: str, tool_context: ToolContext) -> dict:
    """Generate a food photo/visual image for a dish or recipe item using gemini-3.1-flash-lite-image in global region.

    Saves the image as an artifact via tool_context.save_artifact for ADK Playground display,
    and uploads image bytes directly to public Cloud Storage, returning its public HTTPS URL.

    Args:
        prompt: Description of the food item or recipe dish to generate (e.g. 'A plate of freshly baked Margherita Pizza').
        tool_context: ADK ToolContext to register and save the generated image artifact.

    Returns:
        Dictionary containing public_url (https://storage.googleapis.com/<bucket>/<object>), artifact_filename, and status.
    """
    try:
        client = Client(vertexai=True, project=PROJECT_ID, location="global")
        response = client.models.generate_content(
            model="gemini-3.1-flash-lite-image",
            contents=f"Generate a professional food photography photo of: {prompt}",
            config=GenerateContentConfig(
                response_modalities=[Modality.IMAGE, Modality.TEXT]
            ),
        )

        image_bytes = None
        for part in response.candidates[0].content.parts:
            if part.inline_data and part.inline_data.data:
                image_bytes = part.inline_data.data
                break

        if not image_bytes:
            return {"error": "No image data was generated by the model."}

        unique_id = uuid.uuid4().hex[:8]
        clean_name = prompt.lower().replace(" ", "_")[:20]
        filename = f"recipe_{clean_name}_{unique_id}.png"

        # 1. Save artifact with tool_context for Playground Artifacts panel
        if tool_context:
            tool_context.save_artifact(
                filename=filename,
                mime_type="image/png",
                data=image_bytes,
            )

        # 2. Upload image bytes directly to public Cloud Storage bucket
        storage_client = storage.Client(project=PROJECT_ID)
        bucket = storage_client.bucket(BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(image_bytes, content_type="image/png")

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"

        return {
            "status": "success",
            "prompt": prompt,
            "public_url": public_url,
            "artifact_filename": filename,
            "message": f"Successfully generated image for '{prompt}', saved artifact '{filename}', and uploaded to GCS public URL.",
        }
    except Exception as e:
        return {"error": f"Failed to generate recipe image: {str(e)}"}


def generate_recipe_video(prompt: str, tool_context: ToolContext) -> dict:
    """Generate a short cooking demonstration or dish preparation video using Google's Omni model (gemini-omni-flash-preview) in the global region.

    Saves the generated video as an artifact via tool_context.save_artifact for ADK Playground display,
    and uploads video bytes directly to public Cloud Storage, returning its public HTTPS URL.

    Args:
        prompt: Description of the recipe or food item demonstration video to generate (e.g. 'A short video showing fresh pasta being tossed with marinara sauce').
        tool_context: ADK ToolContext to register and save the generated video artifact.

    Returns:
        Dictionary containing public_url (https://storage.googleapis.com/<bucket>/<object>), artifact_filename, and status.
    """
    try:
        client = Client(vertexai=True, project=PROJECT_ID, location="global")

        # Call Google's Omni model (gemini-omni-flash-preview) via Interactions API
        interaction = client.interactions.create(
            model="gemini-omni-flash-preview",
            input=f"A short cooking video demonstration showing how to make: {prompt}",
        )

        video_bytes = None
        if hasattr(interaction, "output_video") and interaction.output_video and getattr(interaction.output_video, "data", None):
            raw_data = interaction.output_video.data
            if isinstance(raw_data, str):
                try:
                    video_bytes = base64.b64decode(raw_data)
                except Exception:
                    video_bytes = raw_data.encode("utf-8")
            else:
                video_bytes = raw_data
        elif hasattr(interaction, "steps") and interaction.steps:
            for step in interaction.steps:
                if getattr(step, "type", "") == "model_output":
                    content_list = getattr(step, "content", [])
                    for item in content_list:
                        if isinstance(item, dict) and item.get("type") == "video" and item.get("data"):
                            video_bytes = base64.b64decode(item["data"])
                            break

        if not video_bytes:
            return {"error": "No video bytes were returned by gemini-omni-flash-preview."}

        unique_id = uuid.uuid4().hex[:8]
        clean_name = prompt.lower().replace(" ", "_")[:20]
        filename = f"recipe_{clean_name}_{unique_id}.mp4"

        # 1. Save artifact with tool_context for Playground Artifacts panel
        if tool_context:
            tool_context.save_artifact(
                filename=filename,
                mime_type="video/mp4",
                data=video_bytes,
            )

        # 2. Upload video bytes directly to public Cloud Storage bucket
        storage_client = storage.Client(project=PROJECT_ID)
        bucket = storage_client.bucket(BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(video_bytes, content_type="video/mp4")

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"

        return {
            "status": "success",
            "prompt": prompt,
            "public_url": public_url,
            "artifact_filename": filename,
            "message": f"Successfully generated video for '{prompt}', saved artifact '{filename}', and uploaded to GCS public URL.",
        }
    except Exception as e:
        return {"error": f"Failed to generate recipe video: {str(e)}"}


def geocode_address(address: str) -> dict:
    """Convert a human-readable street address or location name into latitude/longitude coordinates using Google Maps Geocoding API.

    Args:
        address: The street address or city/location name to geocode (e.g. '1600 Amphitheatre Pkwy, Mountain View, CA').

    Returns:
        Dictionary containing formatted_address, latitude, longitude, and place_id.
    """
    api_key = os.environ.get("GOOGLE_MAPS_API_KEY", "")
    if not api_key:
        return {"error": "GOOGLE_MAPS_API_KEY environment variable is missing."}

    encoded_address = urllib.parse.quote(address.strip())
    url = f"https://maps.googleapis.com/maps/api/geocode/json?address={encoded_address}&key={api_key}"

    try:
        req = urllib.request.Request(url)
        with urllib.request.urlopen(req, timeout=5) as response:
            data = json.loads(response.read().decode())
            results = data.get("results")
            if not results:
                return {"error": f"No geocoding results found for address: {address}"}

            first_result = results[0]
            location = first_result.get("geometry", {}).get("location", {})
            return {
                "formatted_address": first_result.get("formatted_address"),
                "latitude": location.get("lat"),
                "longitude": location.get("lng"),
                "place_id": first_result.get("place_id"),
            }
    except Exception as e:
        return {"error": f"Geocoding API call failed: {str(e)}"}


def find_nearby_places(
    latitude: float, longitude: float, place_type: str = "grocery_store", radius_meters: float = 2000.0
) -> list[dict]:
    """Find nearby points of interest (e.g. grocery stores, supermarkets, bakeries) using Google Places API (New).

    Args:
        latitude: Latitude coordinate.
        longitude: Longitude coordinate.
        place_type: Type of place to search for (e.g. 'grocery_store', 'supermarket', 'bakery', 'restaurant').
        radius_meters: Search radius in meters (default 2000.0 meters).

    Returns:
        List of nearby place dictionaries containing name, address, and location (latitude/longitude).
    """
    api_key = os.environ.get("GOOGLE_MAPS_API_KEY", "")
    if not api_key:
        return [{"error": "GOOGLE_MAPS_API_KEY environment variable is missing."}]

    url = "https://places.googleapis.com/v1/places:searchNearby"
    headers = {
        "Content-Type": "application/json",
        "X-Goog-Api-Key": api_key,
        "X-Goog-FieldMask": "places.displayName,places.formattedAddress,places.location",
    }
    payload = {
        "includedTypes": [place_type],
        "maxResultCount": 5,
        "locationRestriction": {
            "circle": {
                "center": {
                    "latitude": float(latitude),
                    "longitude": float(longitude),
                },
                "radius": float(radius_meters),
            }
        },
    }

    try:
        body = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(url, data=body, headers=headers, method="POST")
        with urllib.request.urlopen(req, timeout=5) as response:
            data = json.loads(response.read().decode())
            places_raw = data.get("places", [])

            results = []
            for p in places_raw:
                results.append({
                    "name": p.get("displayName", {}).get("text"),
                    "address": p.get("formattedAddress"),
                    "location": p.get("location"),
                })
            return results
    except Exception as e:
        return [{"error": f"Places API call failed: {str(e)}"}]


def get_pantry_items(category: str = "") -> list[dict]:
    """Retrieve pantry items from Firestore database.

    Args:
        category: Optional category filter (e.g. 'Dairy & Eggs', 'Grains & Pasta', 'Pantry Staples'). Pass empty string to list all.

    Returns:
        List of pantry item dictionaries containing item_name, category, quantity, unit, and notes.
    """
    db = firestore.Client(project=PROJECT_ID)
    docs = db.collection("pantry_items").stream()
    
    items = []
    for doc in docs:
        data = doc.to_dict()
        if not category or category.lower() in data.get("category", "").lower():
            items.append(data)
            
    return items


def add_or_update_pantry_item(
    item_name: str, category: str, quantity: float, unit: str, notes: str = ""
) -> dict:
    """Add a new item or update an existing item quantity in the pantry Firestore database.

    Args:
        item_name: Name of the pantry item (e.g. 'Organic Eggs', 'Almond Milk').
        category: Category of item (e.g. 'Dairy & Eggs', 'Dairy Alternatives', 'Grains & Pasta').
        quantity: Amount/quantity of the item available.
        unit: Unit of measurement (e.g. 'pcs', 'carton', 'lbs', 'bottle').
        notes: Optional extra details or notes about the item.

    Returns:
        Dictionary confirming the item status and stored data.
    """
    db = firestore.Client(project=PROJECT_ID)
    doc_id = item_name.lower().strip().replace(" ", "_")
    
    item_data = {
        "item_name": item_name,
        "category": category,
        "quantity": float(quantity),
        "unit": unit,
        "notes": notes,
    }
    
    doc_ref = db.collection("pantry_items").document(doc_id)
    doc_ref.set(item_data)
    
    return {"status": "success", "message": f"Updated {item_name} in pantry", "item": item_data}


def generate_grocery_list(recipe_name: str, required_ingredients: list[str]) -> dict:
    """Compare required recipe ingredients against current Firestore pantry inventory,
    and save missing ingredients into the Firestore shopping_list collection.

    Args:
        recipe_name: Name of the recipe or meal (e.g. 'Wild Mushroom Risotto', 'French Omelette').
        required_ingredients: List of ingredient names needed for the recipe.

    Returns:
        Dictionary detailing available ingredients and added shopping list items.
    """
    db = firestore.Client(project=PROJECT_ID)
    pantry_docs = db.collection("pantry_items").stream()
    pantry_names = {doc.to_dict().get("item_name", "").lower(): doc.to_dict() for doc in pantry_docs}

    missing_items = []
    in_stock_items = []

    for ingredient in required_ingredients:
        clean_name = ingredient.strip()
        matched = False
        for p_name in pantry_names:
            if p_name in clean_name.lower() or clean_name.lower() in p_name:
                matched = True
                break
        
        if matched:
            in_stock_items.append(clean_name)
        else:
            missing_items.append(clean_name)
            doc_id = clean_name.lower().replace(" ", "_")
            db.collection("shopping_list").document(doc_id).set({
                "item_name": clean_name,
                "recipe_name": recipe_name,
                "status": "needed",
                "added_at": datetime.datetime.now().isoformat(),
            })

    return {
        "recipe_name": recipe_name,
        "in_stock_ingredients": in_stock_items,
        "shopping_list_added": missing_items,
        "message": f"Added {len(missing_items)} missing items to shopping list in Firestore."
    }


def search_online_recipes(dish_or_ingredient: str) -> list[dict]:
    """Search for real recipes online by dish name or main ingredient using TheMealDB public API.

    Args:
        dish_or_ingredient: Name of the dish (e.g. 'Arrabiata', 'Risotto') or main ingredient (e.g. 'Chicken', 'Egg').

    Returns:
        List of matching recipe dicts containing title, category, area, instructions, thumbnail URL, and ingredients list.
    """
    api_key = os.environ.get("MEALDB_API_KEY", "1")
    encoded_query = urllib.parse.quote(dish_or_ingredient.strip())
    url = f"https://www.themealdb.com/api/json/v1/{api_key}/search.php?s={encoded_query}"

    try:
        req = urllib.request.Request(url, headers={"User-Agent": "SmartPantryAgent/1.0"})
        with urllib.request.urlopen(req, timeout=5) as response:
            data = json.loads(response.read().decode())
            meals = data.get("meals")

            if not meals:
                filter_url = f"https://www.themealdb.com/api/json/v1/{api_key}/filter.php?i={encoded_query}"
                req_filter = urllib.request.Request(filter_url, headers={"User-Agent": "SmartPantryAgent/1.0"})
                with urllib.request.urlopen(req_filter, timeout=5) as filter_resp:
                    filter_data = json.loads(filter_resp.read().decode())
                    meals = filter_data.get("meals")

            if not meals:
                return []

            results = []
            for meal in meals[:3]:
                ingredients = []
                for i in range(1, 21):
                    ing = meal.get(f"strIngredient{i}")
                    meas = meal.get(f"strMeasure{i}")
                    if ing and ing.strip():
                        ingredients.append(f"{meas.strip() if meas else ''} {ing.strip()}".strip())

                results.append({
                    "title": meal.get("strMeal"),
                    "category": meal.get("strCategory", "Main"),
                    "area": meal.get("strArea", "International"),
                    "instructions": meal.get("strInstructions", ""),
                    "image_url": meal.get("strMealThumb", ""),
                    "ingredients": ingredients,
                })
            return results
    except Exception as e:
        return [{"error": f"Failed to fetch recipe from public API: {str(e)}"}]


def get_weather(query: str) -> str:
    """Simulates a web search. Use it get information on weather.

    Args:
        query: A string containing the location to get weather information for.

    Returns:
        A string with the simulated weather information for the queried location.
    """
    if "sf" in query.lower() or "san francisco" in query.lower():
        return "It's 60 degrees and foggy."
    return "It's 90 degrees and sunny."


def get_current_time(query: str) -> str:
    """Simulates getting the current time for a city.

    Args:
        query: The name of the city to get the current time for.

    Returns:
        A string with the current time information.
    """
    if "sf" in query.lower() or "san francisco" in query.lower():
        tz_identifier = "America/Los_Angeles"
    else:
        return f"Sorry, I don't have timezone information for query: {query}."

    tz = ZoneInfo(tz_identifier)
    now = datetime.datetime.now(tz)
    return f"The current time for query {query} is {now.strftime('%Y-%m-%d %H:%M:%S %Z%z')}"


